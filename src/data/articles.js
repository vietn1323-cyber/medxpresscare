// Helper tạo Slug chuẩn SEO từ tiêu đề tiếng Việt
export const slugify = (text) => {
  if (!text) return '';
  return text
    .toString()
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/đ/g, 'd')
    .replace(/[^a-z0-9 -]/g, '')
    .trim()
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-+|-+$/g, '');
};

// Helper đánh giá và tính điểm SEO On-Page thời gian thực
export const calculateSeoScore = (art) => {
  let score = 0;
  const checks = [];

  const title = (art.title || '').trim();
  const metaTitle = (art.metaTitle || title).trim();
  const metaDesc = (art.metaDescription || art.summary || '').trim();
  const keyword = (art.focusKeyword || '').toLowerCase().trim();
  const slug = (art.slug || '').trim();
  const content = (art.content || '').toLowerCase();
  const hasImage = !!art.image;
  const hasAlt = !!(art.imageAlt || '').trim();

  // 1. Tiêu đề SEO (15 điểm)
  if (metaTitle.length >= 40 && metaTitle.length <= 65) {
    score += 15;
    checks.push({ label: 'Độ dài Meta Title tối ưu (40 - 65 ký tự)', passed: true, detail: `${metaTitle.length}/60 ký tự` });
  } else if (metaTitle.length > 0) {
    score += 8;
    checks.push({ label: 'Độ dài Meta Title chưa lý tưởng (khuyến nghị 40-65)', passed: false, detail: `${metaTitle.length} ký tự` });
  } else {
    checks.push({ label: 'Chưa có Meta Title', passed: false });
  }

  // 2. Mô tả Meta Description (15 điểm)
  if (metaDesc.length >= 120 && metaDesc.length <= 165) {
    score += 15;
    checks.push({ label: 'Độ dài Meta Description lý tưởng (120 - 165 ký tự)', passed: true, detail: `${metaDesc.length}/160 ký tự` });
  } else if (metaDesc.length > 0) {
    score += 8;
    checks.push({ label: 'Độ dài Meta Description nên từ 120-165 ký tự', passed: false, detail: `${metaDesc.length} ký tự` });
  } else {
    checks.push({ label: 'Chưa có Meta Description', passed: false });
  }

  // 3. Từ khóa chính (Focus Keyword) (15 điểm)
  if (keyword.length > 2) {
    score += 15;
    checks.push({ label: `Đã thiết lập từ khóa chính: "${keyword}"`, passed: true });
  } else {
    checks.push({ label: 'Chưa đặt từ khóa chính (Focus Keyword)', passed: false });
  }

  // 4. Từ khóa xuất hiện trong Tiêu đề (15 điểm)
  if (keyword.length > 2 && metaTitle.toLowerCase().includes(keyword)) {
    score += 15;
    checks.push({ label: 'Từ khóa chính có mặt trong Tiêu đề SEO', passed: true });
  } else {
    checks.push({ label: 'Từ khóa chính nên xuất hiện trong Tiêu đề SEO', passed: false });
  }

  // 5. Từ khóa xuất hiện trong Mô tả Meta (15 điểm)
  if (keyword.length > 2 && metaDesc.toLowerCase().includes(keyword)) {
    score += 15;
    checks.push({ label: 'Từ khóa chính có mặt trong Meta Description', passed: true });
  } else {
    checks.push({ label: 'Từ khóa chính nên xuất hiện trong Meta Description', passed: false });
  }

  // 6. Đường dẫn tĩnh Slug thân thiện SEO (10 điểm)
  if (slug && /^[a-z0-9-]+$/.test(slug) && slug.length >= 5) {
    score += 10;
    checks.push({ label: 'Slug URL ngắn gọn, chuẩn ký tự không dấu', passed: true, detail: slug });
  } else {
    checks.push({ label: 'Slug URL chưa chuẩn SEO (cần chữ thường, gạch ngang)', passed: false });
  }

  // 7. Hình ảnh đại diện & Thẻ ALT (15 điểm)
  if (hasImage && hasAlt) {
    score += 15;
    checks.push({ label: 'Có ảnh đại diện và đã điền thẻ ALT tối ưu tìm kiếm hình ảnh', passed: true });
  } else if (hasImage) {
    score += 7;
    checks.push({ label: 'Có ảnh nhưng còn thiếu thẻ mô tả ALT cho ảnh', passed: false });
  } else {
    checks.push({ label: 'Chưa có ảnh đại diện cho bài viết', passed: false });
  }

  return {
    score: Math.min(100, score),
    checks
  };
};
